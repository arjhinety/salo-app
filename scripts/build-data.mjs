// Converts the bundled Salo Evening Dataset CSVs (data/salo-evening-dataset) into
// src/data/dataset.generated.ts. Every CSV is checked against SHA256SUMS first, so the app
// can only ever be built from the exact published v1.2 files.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(import.meta.dirname, '..', 'data', 'salo-evening-dataset');
const OUT = join(import.meta.dirname, '..', 'src', 'data', 'dataset.generated.ts');

// RFC 4180: quoted fields may hold commas, quotes ("") and newlines.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, j) => [h, r[j]])));
}

const sums = Object.fromEntries(
  readFileSync(join(DIR, 'SHA256SUMS'), 'utf8').trim().split('\n').map((l) => {
    const [h, name] = l.split(/\s+/);
    return [name, h];
  }),
);
function table(name) {
  const buf = readFileSync(join(DIR, `${name}.csv`));
  const h = createHash('sha256').update(buf).digest('hex');
  if (h !== sums[`${name}.csv`]) throw new Error(`${name}.csv does not match SHA256SUMS (got ${h})`);
  return parseCsv(buf.toString('utf8'));
}

const minute = (hhmm) => { const [h, m] = hhmm.split(':').map(Number); return h * 60 + m; };
const bool = (s) => s === 'True';
const num = Number;

const pantries = table('pantries').map((r) => ({
  id: r.pantry_id, name: r.pantry_name, type: r.pantry_type, street: r.street,
  opensMinute: minute(r.opens), closesMinute: minute(r.closes), hasFridge: bool(r.has_fridge),
  fridgeCapacityKg: num(r.fridge_capacity_kg), dryStorageKg: num(r.dry_storage_kg), anchor: bool(r.anchor),
  lat: num(r.lat), lon: num(r.lon),
}));
const donors = table('donors').map((r) => ({
  id: r.donor_id, name: r.donor_name, type: r.donor_type, street: r.street,
  closingMinute: minute(r.closing_time), anchor: bool(r.anchor),
  lat: num(r.lat), lon: num(r.lon),
}));
const drivers = table('drivers').map((r) => ({
  id: r.driver_id, name: r.display_name, vehicle: r.vehicle, capacityLoadUnits: num(r.capacity_load_units),
  street: r.street, availableFromMinute: minute(r.available_from), availableToMinute: minute(r.available_to),
  tuningRuns: num(r.tuning_runs), tuningShows: num(r.tuning_shows),
  frozenReliability: num(r.reliability_estimate_frozen), anchor: bool(r.anchor),
  homeLat: num(r.home_lat), homeLon: num(r.home_lon),
}));
const roads = table('road_distances').map((r) => ({
  donorId: r.donor_id, pantryId: r.pantry_id, roadKm: num(r.road_km),
  minutes: { motorcycle: num(r.est_min_motorcycle), car: num(r.est_min_car),
    bicycle: num(r.est_min_bicycle), tricycle: num(r.est_min_tricycle) },
}));
const driverLegs = table('driver_distances').map((r) => ({
  driverId: r.driver_id, donorId: r.donor_id, roadKm: num(r.road_km), minutes: num(r.est_min),
}));
const storage = Object.fromEntries(table('storage_rules').map((r) => [r.food_item, num(r.max_hours_unrefrigerated)]));
const needsBy = {};
for (const r of table('pantry_needs')) {
  (needsBy[r.evening_id] ??= []).push({ pantryId: r.pantry_id, isOpen: bool(r.is_open), needKg: num(r.need_kg) });
}
const lotsBy = {};
for (const r of table('food_offers')) {
  const item = {
    foodItem: r.food_item, foodItemFil: r.food_item_fil, foodCategory: r.food_category, quantity: num(r.quantity),
    unit: r.unit, estKg: num(r.est_kg), loadUnits: num(r.load_units), needsFridgeIfKept: bool(r.needs_fridge_if_kept),
    maxHoursUnrefrigerated: storage[r.food_item],
  };
  (lotsBy[r.evening_id] ??= []).push({
    id: r.lot_id, donorId: r.donor_id, items: [item], estKg: item.estKg, loadUnits: item.loadUnits,
    postedMinute: minute(r.posted_at), pickupByMinute: minute(r.pickup_by), origin: 'dataset',
  });
}
const evenings = table('evenings').map((r) => ({
  id: r.evening_id, seed: num(r.seed), split: r.split, date: r.date,
  needs: needsBy[r.evening_id],
  lots: lotsBy[r.evening_id].sort((a, b) => a.postedMinute - b.postedMinute || (a.id < b.id ? -1 : 1)),
}));
// D-b: minutes late are drawn from the tuning runs' completed_late values only.
const lateMinutes = table('driver_runs').filter((r) => r.outcome === 'completed_late').map((r) => num(r.minutes_late));

const data = { version: 'v1.2', pantries, donors, drivers, roads, driverLegs, evenings, lateMinutes };
writeFileSync(OUT, `// Generated by scripts/build-data.mjs from data/salo-evening-dataset (Salo Evening Dataset ${data.version}).\n` +
  `// Do not edit by hand: run \`npm run build-data\`.\n` +
  `import type { RawDataset } from './rawTypes';\n\n` +
  `export const RAW: RawDataset = ${JSON.stringify(data)};\n`);
console.log(`wrote ${OUT}: ${pantries.length} pantries, ${donors.length} donors, ${drivers.length} drivers, ` +
  `${roads.length} road legs, ${driverLegs.length} driver legs, ${evenings.length} evenings, ` +
  `${evenings.reduce((s, e) => s + e.lots.length, 0)} lots, ${lateMinutes.length} late-minute samples`);
