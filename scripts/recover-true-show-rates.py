"""Recovers each driver's hidden true show rate (the dataset generator's p_show) for the engine.

Decision "Hidden true show rate" (docs/decisions.md): the simulated world draws driver behaviour from
these rates, while the agents only ever learn from the tuning counts.

How: copy the pinned dataset build (build_dataset.py v1.2) into a temporary folder, add read-only
instrumentation that records p_show per driver (no extra random draws), run it, and check that every
CSV it writes is byte-identical to the bundled data/salo-evening-dataset files. Only then write
src/engine/hiddenTruth.generated.ts. R. Dizon's history was hand-set in the generator (no p_show), so he
gets one fixed draw from Beta(shows + 1, misses + 1): numpy default_rng(20260927), one draw per driver
in drivers.csv order, R. Dizon's being the first (0.817), exactly as in the experiment Arjhine approved.

    python scripts/recover-true-show-rates.py ../salo-evening-dataset-repo
"""
import hashlib, json, os, shutil, subprocess, sys, tempfile

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(APP, "..", "salo-evening-dataset-repo"))
DATA = os.path.join(APP, "data", "salo-evening-dataset")
OUT = os.path.join(APP, "src", "engine", "hiddenTruth.generated.ts")
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()

with tempfile.TemporaryDirectory() as tmp:
    for f in ["build_dataset.py", "messages.py", "params.json", "storage_rules.json"]:
        shutil.copy(os.path.join(REPO, f), tmp)
    shutil.copytree(os.path.join(REPO, "sources"), os.path.join(tmp, "sources"))
    src = open(os.path.join(tmp, "build_dataset.py"), encoding="utf-8").read()
    hook = '    planned_outcomes[f"V{i:02d}"] = outcomes\n'
    assert src.count(hook) == 1 and src.count("drivers, planned_outcomes = [], {}\n") == 1
    src = src.replace("drivers, planned_outcomes = [], {}\n", "drivers, planned_outcomes = [], {}\nPSHOW = {}\n", 1)
    src = src.replace(hook, hook + '    PSHOW[f"V{i:02d}"] = p_show\n', 1)
    src += '\nimport json as _j\n_j.dump(PSHOW, open("pshow.json", "w"))\n'
    open(os.path.join(tmp, "build_dataset.py"), "w", encoding="utf-8").write(src)
    subprocess.run([sys.executable, "build_dataset.py"], cwd=tmp, check=True, stdout=subprocess.DEVNULL)
    bundled = [f for f in os.listdir(DATA) if f.endswith(".csv")]
    bad = [f for f in bundled if sha(os.path.join(tmp, "salo-evening-dataset", f)) != sha(os.path.join(DATA, f))]
    if bad:
        sys.exit(f"instrumented build differs from the bundled data: {bad}")
    pshow = json.load(open(os.path.join(tmp, "pshow.json")))

import csv
import numpy as np
drivers = list(csv.DictReader(open(os.path.join(DATA, "drivers.csv"), encoding="utf-8")))
rng = np.random.default_rng(20260927)
posterior = {d["driver_id"]: float(rng.beta(int(d["tuning_shows"]) + 1, int(d["tuning_runs"]) - int(d["tuning_shows"]) + 1))
             for d in drivers}
rates = {}
for d in drivers:
    p = pshow.get(d["driver_id"])
    if p is None:  # hand-set history (R. Dizon): the fixed posterior draw
        p = posterior[d["driver_id"]]
    rates[d["driver_id"]] = round(p, 6)
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by scripts/recover-true-show-rates.py. Do not edit.\n"
             "// HIDDEN GROUND TRUTH: only the simulated world reads this. Agents, messages and the UI never do.\n"
             "export const TRUE_SHOW_RATE: Readonly<Record<string, number>> = "
             + json.dumps(rates, indent=2) + ";\n")
print(f"verified {len(bundled)} CSVs byte-identical; wrote {len(rates)} rates to {OUT}; V01 = {rates['V01']}")
