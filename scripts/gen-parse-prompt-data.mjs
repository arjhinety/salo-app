// Generates the Edge Function's build-time data from the same sources the laptop proxy uses.
//   supabase/functions/parse/promptData.ts  canonical (food_item, unit) pairs and the three prompt examples
//   supabase/functions/parse/buildInfo.ts   the canonical output JSON Schema and the LF-normalised source text of
//                                           schema.ts and parse.ts (inputs to request_config_sha256)
//
// Data rule (docs/decisions.md, "Parser development data: tuning evenings only"): the only dataset file read here is
// data/parse-dev/donor_messages_tuning.csv, filtered to evening_id E01..E10 first, then asserted. Never donor_messages.csv,
// pilot (E11-E20) or main (E21-E30) rows.
//
// Usage:  node scripts/gen-parse-prompt-data.mjs            (writes the two files)
//         node scripts/gen-parse-prompt-data.mjs --check    (exits 1 if the files on disk are stale)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseCsv } from "../server/src/csv.js";
import { PROMPT_EXAMPLES, canonicalPairs } from "../server/src/prompt.js";
import { ModelOutput } from "../server/src/schema.js";
import { canonicalJson, normalizeLf } from "../server/src/requestConfig.js";


const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const CSV_PATH = `${ROOT}data/parse-dev/donor_messages_tuning.csv`;
export const FN_DIR = `${ROOT}supabase/functions/parse/`;
export const PROMPT_DATA_PATH = `${FN_DIR}promptData.ts`;
export const BUILD_INFO_PATH = `${FN_DIR}buildInfo.ts`;
export const EXPECTED_SHA256_PREFIX = "4f269299"; // docs/decisions.md, 2026-10-20
export const FILTER_TEXT = 'evening_id matches /^E(0[1-9]|10)$/ (E01..E10); split === "tuning"; exactly 170 rows';
const EVENING_RE = /^E(0[1-9]|10)$/;
const TUNING_ROW_COUNT = 170;

const sha256Hex = (buf) => createHash("sha256").update(buf).digest("hex");

// Filter first, then assert. Throws on any mismatch so the generator never writes a wrong prompt.
export function loadTuningRows(csvPath = CSV_PATH) {
  const raw = readFileSync(csvPath);
  const sha = sha256Hex(raw);
  if (!sha.startsWith(EXPECTED_SHA256_PREFIX)) throw new Error(`tuning CSV sha256 ${sha} does not start with ${EXPECTED_SHA256_PREFIX}`);
  const all = parseCsv(raw.toString("utf8"));
  const kept = all.filter((r) => EVENING_RE.test(r.evening_id));
  if (kept.length !== all.length) throw new Error(`tuning CSV: ${all.length - kept.length} row(s) outside E01..E10`);
  if (kept.some((r) => r.split !== "tuning")) throw new Error("tuning CSV: a row has split != tuning");
  if (kept.length !== TUNING_ROW_COUNT) throw new Error(`tuning CSV: expected ${TUNING_ROW_COUNT} rows, got ${kept.length}`);
  return { rows: kept, sha };
}

// Each example: verbatim text from its tuning row, and the gold values in the example output must match the row.
export function assertExamples(rows) {
  for (const e of PROMPT_EXAMPLES) {
    const row = rows.find((r) => r.message_id === e.message_id);
    if (!row) throw new Error(`${e.message_id} is not a tuning row`);
    if (row.message_text !== e.text) throw new Error(`${e.message_id} text is not verbatim`);
    const item = e.output.items[0];
    if (row.gold_food_item !== item.food_item || Number(row.gold_quantity) !== item.quantity
      || row.gold_unit !== item.unit || row.gold_pickup_by !== e.output.pickup_by) {
      throw new Error(`${e.message_id} gold values do not match its example output`);
    }
  }
}

const tsString = (s) => JSON.stringify(s);

export function generatePromptData(rows, sha) {
  const pairs = canonicalPairs(rows);
  const examples = PROMPT_EXAMPLES.map((e) => ({ message_id: e.message_id, text: e.text, output: e.output }));
  const lines = [];
  lines.push("// GENERATED by scripts/gen-parse-prompt-data.mjs. Do not edit by hand; rerun the script.");
  lines.push("// Source: data/parse-dev/donor_messages_tuning.csv");
  lines.push(`// Source sha256: ${sha}`);
  lines.push(`// Filter: ${FILTER_TEXT}.`);
  lines.push("// Canonical pairs: distinct (gold_food_item, gold_unit) of the 170 rows, sorted as server/src/prompt.js sorts them.");
  lines.push("// Examples: M0001 (E01), M0008 (E01), M0025 (E02), verbatim text and gold values checked against the file.");
  lines.push("");
  lines.push(`export const SOURCE_SHA256 = ${tsString(sha)};`);
  lines.push(`export const TUNING_ROW_COUNT = ${rows.length};`);
  lines.push("");
  lines.push("export const CANONICAL_PAIRS: { food_item: string; unit: string }[] = [");
  for (const p of pairs) lines.push(`  { food_item: ${tsString(p.food_item)}, unit: ${tsString(p.unit)} },`);
  lines.push("];");
  lines.push("");
  lines.push("export const PROMPT_EXAMPLES = [");
  for (const e of examples) {
    lines.push("  {");
    lines.push(`    message_id: ${tsString(e.message_id)},`);
    lines.push(`    text: ${tsString(e.text)},`);
    lines.push(`    output: ${JSON.stringify(e.output)},`);
    lines.push("  },");
  }
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

// The output JSON Schema exactly as the laptop proxy sends it: zodOutputFormat(ModelOutput) from the server's own SDK and zod.
export function serverOutputSchemaCanonical() {
  const serverRequire = createRequire(`${ROOT}server/package.json`);
  const { zodOutputFormat } = serverRequire("@anthropic-ai/sdk/helpers/zod");
  return canonicalJson(zodOutputFormat(ModelOutput).schema);
}

// buildInfo.ts holds digests, not source text. The Supabase CLI bundler scans every string literal for import
// specifiers, so embedded TypeScript source (which contains import lines) made it fail to bundle.
export function generateBuildInfo(schemaTsText, parseTsText, schemaCanonical) {
  const lf = (t) => sha256Hex(Buffer.from(normalizeLf(t), "utf8"));
  return [
    "// GENERATED by scripts/gen-parse-prompt-data.mjs. Do not edit by hand; rerun the script.",
    "// OUTPUT_SCHEMA_SHA256: sha256 of the canonical JSON of zodOutputFormat(ModelOutput).schema, built by the laptop proxy.",
    "// SCHEMA_TS_LF_SHA256 and PARSE_TS_LF_SHA256: sha256 of schema.ts and parse.ts with LF line endings, as they were at",
    "// generation. request_config_sha256 (requestConfig.ts) hashes them. The drift test fails when they differ from the files.",
    "",
    `export const OUTPUT_SCHEMA_SHA256 = ${tsString(sha256Hex(Buffer.from(schemaCanonical, "utf8")))};`,
    "",
    `export const SCHEMA_TS_LF_SHA256 = ${tsString(lf(schemaTsText))};`,
    "",
    `export const PARSE_TS_LF_SHA256 = ${tsString(lf(parseTsText))};`,
    "",
  ].join("\n");
}

// Pure: returns the two file contents from the current sources. Used by the script and by the Node parity test.
export function generateAll() {
  const { rows, sha } = loadTuningRows();
  assertExamples(rows);
  const schemaTs = readFileSync(`${FN_DIR}schema.ts`, "utf8");
  const parseTs = readFileSync(`${FN_DIR}parse.ts`, "utf8");
  return {
    promptData: generatePromptData(rows, sha),
    buildInfo: generateBuildInfo(schemaTs, parseTs, serverOutputSchemaCanonical()),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const out = generateAll();
  const targets = [[PROMPT_DATA_PATH, out.promptData], [BUILD_INFO_PATH, out.buildInfo]];
  if (check) {
    const stale = targets.filter(([p, text]) => !existsSync(p) || readFileSync(p, "utf8") !== text).map(([p]) => p);
    if (stale.length) {
      console.error(`stale generated file(s): ${stale.join(", ")}. Run: node scripts/gen-parse-prompt-data.mjs`);
      process.exit(1);
    }
    console.log("generated files are up to date");
    return;
  }
  for (const [p, text] of targets) writeFileSync(p, text, "utf8");
  console.log(`wrote ${PROMPT_DATA_PATH}`);
  console.log(`wrote ${BUILD_INFO_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
