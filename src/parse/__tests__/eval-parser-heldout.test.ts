/**
 * Scores the rule-based fallback on the held-out pilot and main messages (free, offline). Runs only with EVAL_HELDOUT=1.
 * Same scorer as the tuning fallback (parseRules + scoreResponse). Writes docs/reports/parser-fallback-pilot.md and
 * docs/reports/parser-fallback-main.md. Scores are on the raw ParseResponse, before any catalog mapping.
 *
 * Failing messages are counted, not listed: a held-out message must not be used to change the parser.
 * Template-generated messages, so every number is an optimistic upper bound. The fallback's vocabulary was built from the
 * tuning evenings only, so these splits are out-of-sample for it.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { parseRules } from '../rules';
import { scoreResponse } from '../eval/score';
import { HELDOUT_SPLITS, heldoutLabel } from '../eval/heldout';
import type { ParseResponse } from '../types';
import { loadHeldoutRows } from './heldoutCorpus';
import type { TuningRow } from './tuningCorpus';

const run = process.env.EVAL_HELDOUT === '1' ? describe : describe.skip;
const REPORTS = join(__dirname, '..', '..', '..', 'docs', 'reports');

interface Counts {
  n: number;
  food: number;
  quantity: number;
  unit: number;
  pickup: number;
  all: number;
}

const emptyCounts = (): Counts => ({ n: 0, food: 0, quantity: 0, unit: 0, pickup: 0, all: 0 });

function add(c: Counts, s: { food: boolean; quantity: boolean; unit: boolean; pickup: boolean; all: boolean }): void {
  c.n++;
  if (s.food) c.food++;
  if (s.quantity) c.quantity++;
  if (s.unit) c.unit++;
  if (s.pickup) c.pickup++;
  if (s.all) c.all++;
}

const pct = (k: number, n: number): string => (n === 0 ? '-' : `${k}/${n} (${((100 * k) / n).toFixed(1)}%)`);

function table(title: string, groups: Map<string, Counts>): string[] {
  const lines = [`### ${title}`, '', '| group | rows | food | quantity | unit | pickup_by | all four |', '|---|---|---|---|---|---|---|'];
  for (const [k, c] of [...groups].sort()) {
    lines.push(`| ${k} | ${c.n} | ${pct(c.food, c.n)} | ${pct(c.quantity, c.n)} | ${pct(c.unit, c.n)} | ${pct(c.pickup, c.n)} | ${pct(c.all, c.n)} |`);
  }
  return [...lines, ''];
}

function report(split: 'pilot' | 'main', rows: TuningRow[]): string {
  const spec = HELDOUT_SPLITS[split];
  const overall = emptyCounts();
  const byLang = new Map<string, Counts>();
  const byDiff = new Map<string, Counts>();
  const bucket = (m: Map<string, Counts>, key: string): Counts => {
    let c = m.get(key);
    if (!c) {
      c = emptyCounts();
      m.set(key, c);
    }
    return c;
  };
  let clar = 0;
  let clarWithMissing = 0;
  let failing = 0;
  for (const row of rows) {
    const resp: ParseResponse = parseRules(row.message_text);
    const s = scoreResponse(row, resp);
    add(overall, s);
    add(bucket(byLang, row.language), s);
    add(bucket(byDiff, row.difficulty), s);
    if (row.requires_clarification) {
      clar++;
      if (resp.missing.length > 0) clarWithMissing++;
    }
    if (!s.all) failing++;
  }
  const field = (k: number): string => pct(k, overall.n);
  return [
    `# Parser held-out evaluation: rule-based fallback, ${split} messages`,
    '',
    `**${heldoutLabel(spec)}.**`,
    '',
    `**Scope: held-out ${split} messages only.** ${rows.length} rows, evenings ${spec.evenings}, from the evening dataset v1.3 ` +
      `(\`donor_messages.csv\`, split \`${spec.datasetLabel}\`; the evening comes from \`food_offers.csv\`). ` +
      'The messages are template-generated, so every number here is an **optimistic upper bound**.',
    '',
    '**Out-of-sample for the fallback.** Its vocabulary, synonyms and time phrases were built from the tuning evenings E01 to E10 only, ' +
      'so these splits were not used to build it. The canonical food list is the 21 foods of the tuning gold labels, so a gold food outside it ' +
      'cannot match and counts as wrong.',
    '',
    'Scores are computed on the raw ParseResponse (src/parse output), before any catalog mapping.',
    '',
    'Generated by `EVAL_HELDOUT=1 npx jest src/parse/__tests__/eval-parser-heldout.test.ts`. Parser: `parseRules` (source "fallback").',
    '',
    '## Headline',
    '',
    `- Overall, all four fields correct: ${field(overall.all)}`,
    `- Food item exact match: ${field(overall.food)}`,
    `- Quantity: ${field(overall.quantity)}`,
    `- Unit: ${field(overall.unit)}`,
    `- pickup_by: ${field(overall.pickup)}`,
    `- Rows that require clarification (gold \`requires_clarification\` = True): ${clar}. Of these, ${pct(clarWithMissing, clar)} have a non-empty \`missing\` list.`,
    `- Rows with at least one field wrong: ${failing} of ${rows.length}. The failing messages are not listed: a held-out message must not be used to change the parser.`,
    '',
    '## By group',
    '',
    ...table('By language', byLang),
    ...table('By difficulty', byDiff),
  ].join('\n');
}

run('held-out parser evaluation, rule-based fallback (EVAL_HELDOUT=1)', () => {
  for (const split of ['pilot', 'main'] as const) {
    it(`scores the fallback on held-out ${split} and writes the report`, () => {
      const rows = loadHeldoutRows(split);
      mkdirSync(REPORTS, { recursive: true });
      writeFileSync(join(REPORTS, `parser-fallback-${split}.md`), report(split, rows));
      expect(rows.length).toBe(HELDOUT_SPLITS[split].count);
    });
  }
});
