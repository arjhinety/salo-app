/**
 * Scores the rule-based fallback on the 170 tuning messages (E01..E10). Runs only with EVAL=1, like REPORT=1 in
 * src/engine/__tests__/report.test.ts. Writes docs/reports/parser-tuning-fallback.md.
 *
 * Scoring boundary: scores are computed on the raw ParseResponse (src/parse output), before any catalog mapping.
 * This file imports nothing from src/donor or src/data (checked by imports.test.ts). Tuning messages only.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { parseRules } from '../rules';
import { scoreResponse } from '../eval/score';
import type { ParseResponse } from '../types';
import { loadTuningRows, type TuningRow } from './tuningCorpus';

const run = process.env.EVAL === '1' ? describe : describe.skip;
const REPORT_PATH = join(__dirname, '..', '..', '..', 'docs', 'reports', 'parser-tuning-fallback.md');

interface Counts {
  n: number;
  food: number;
  quantity: number;
  unit: number;
  pickup: number;
  all: number;
}

interface RowResult {
  row: TuningRow;
  resp: ParseResponse;
  food: boolean;
  quantity: boolean;
  unit: boolean;
  pickup: boolean;
}

const emptyCounts = (): Counts => ({ n: 0, food: 0, quantity: 0, unit: 0, pickup: 0, all: 0 });

function add(c: Counts, r: RowResult): void {
  c.n++;
  if (r.food) c.food++;
  if (r.quantity) c.quantity++;
  if (r.unit) c.unit++;
  if (r.pickup) c.pickup++;
  if (r.food && r.quantity && r.unit && r.pickup) c.all++;
}

const pct = (k: number, n: number): string => (n === 0 ? '-' : `${k}/${n} (${((100 * k) / n).toFixed(1)}%)`);

function scoreRow(row: TuningRow): RowResult {
  const resp = parseRules(row.message_text);
  const s = scoreResponse(row, resp);
  return { row, resp, food: s.food, quantity: s.quantity, unit: s.unit, pickup: s.pickup };
}

function table(title: string, groups: Map<string, Counts>): string[] {
  const lines = [`### ${title}`, '', '| group | rows | food | quantity | unit | pickup_by | all four |', '|---|---|---|---|---|---|---|'];
  for (const [k, c] of [...groups].sort()) {
    lines.push(`| ${k} | ${c.n} | ${pct(c.food, c.n)} | ${pct(c.quantity, c.n)} | ${pct(c.unit, c.n)} | ${pct(c.pickup, c.n)} | ${pct(c.all, c.n)} |`);
  }
  return [...lines, ''];
}

run('parser tuning evaluation (EVAL=1)', () => {
  const rows = loadTuningRows();
  const results = rows.map(scoreRow);

  it('scores all 170 tuning rows and writes the report', () => {
    const overall = emptyCounts();
    const byLang = new Map<string, Counts>();
    const byDiff = new Map<string, Counts>();
    const bucket = (m: Map<string, Counts>, key: string): Counts => {
      let c = m.get(key);
      if (!c) {
        c = emptyCounts();
        m.set(key, c);
      }
      return c;
    };
    for (const r of results) {
      add(overall, r);
      add(bucket(byLang, r.row.language), r);
      add(bucket(byDiff, r.row.difficulty), r);
    }
    const clar = results.filter((r) => r.row.requires_clarification);
    const clarWithMissing = clar.filter((r) => r.resp.missing.length > 0).length;
    const failing = results.filter((r) => !(r.food && r.quantity && r.unit && r.pickup));
    const fieldFails = (f: keyof Pick<RowResult, 'food' | 'quantity' | 'unit' | 'pickup'>) =>
      results.filter((r) => !r[f]).map((r) => r.row.message_id).join(', ') || 'none';

    const lines: string[] = [
      '# Parser tuning evaluation: rule-based fallback',
      '',
      '**Scope: tuning messages only.** 170 rows, evenings E01 to E10, from `data/parse-dev/donor_messages_tuning.csv`.',
      'The messages are template-generated, so every number here is an **optimistic upper bound**.',
      '**No pilot or main messages were read or scored.** The evaluation was not run on any other split.',
      '',
      '**Scoring boundary:** Scores are computed on the raw ParseResponse (src/parse output), before any catalog mapping.',
      '',
      '**In-sample score:** the fallback\'s vocabulary, synonyms and time phrases were built from the same 170 tuning messages it is scored on. This score is in-sample and must never be quoted as expected accuracy.',
      '',
      `Generated by \`EVAL=1 npx jest src/parse/__tests__/eval-parser-tuning.test.ts\`. Parser: \`parseRules\` (source "fallback").`,
      '',
      '## Headline',
      '',
      `- Overall, all four fields correct: ${pct(overall.all, overall.n)}`,
      `- Food item exact match: ${pct(overall.food, overall.n)}`,
      `- Quantity: ${pct(overall.quantity, overall.n)}`,
      `- Unit: ${pct(overall.unit, overall.n)}`,
      `- pickup_by: ${pct(overall.pickup, overall.n)}`,
      `- Rows that require clarification (gold \`requires_clarification\` = True): ${clar.length}. Of these, ${pct(clarWithMissing, clar.length)} have a non-empty \`missing\` list.`,
      '',
      '## By group',
      '',
      ...table('By language', byLang),
      ...table('By difficulty', byDiff),
      '## Failing rows',
      '',
      `Rows with at least one field wrong: ${failing.length} of ${results.length}.`,
      '',
      `- food item wrong: ${fieldFails('food')}`,
      `- quantity wrong: ${fieldFails('quantity')}`,
      `- unit wrong: ${fieldFails('unit')}`,
      `- pickup_by wrong: ${fieldFails('pickup')}`,
      '',
    ];
    mkdirSync(join(__dirname, '..', '..', '..', 'docs', 'reports'), { recursive: true });
    writeFileSync(REPORT_PATH, lines.join('\n'));

    if (process.env.EVAL_DEBUG_OUT) {
      const dbg = failing.map(
        (r) => `${r.row.message_id} gold=${JSON.stringify({ f: r.row.gold_food_item, q: r.row.gold_quantity, u: r.row.gold_unit, p: r.row.gold_pickup_by })} got=${JSON.stringify(r.resp)}`,
      );
      writeFileSync(process.env.EVAL_DEBUG_OUT, dbg.join('\n'));
    }
    expect(overall.n).toBe(170);
  });
});
