/**
 * Output of the gated main run: the TypeScript module the Results screen reads, and docs/reports/m6-main.md.
 * Pure: takes the stored record (and the evenings, for the ceiling definition), returns text. No engine call, no file access.
 */

const LABEL: Record<PolicyId, string> = {
  salo: 'Agents (Salo)',
  central_greedy: 'Central greedy',
  fcfs: 'First come, first served',
  nearest: 'Nearest pantry',
};
const ORDER: PolicyId[] = ['salo', 'central_greedy', 'fcfs', 'nearest'];

const f2 = (x: number) => x.toFixed(2);
const f3 = (x: number) => x.toFixed(3);
const signed = (x: number, d: number) => `${x >= 0 ? '+' : '−'}${Math.abs(x).toFixed(d)}`;

/** The module text: a typed constant holding the stored record. */
export function renderGeneratedModule(p: PersistedMainResults): string {
  return [
    '// Generated by src/tuning/__tests__/m6-main-run.test.ts (M6_MAIN=1) on the main evenings E21-E64. Do not edit by hand.',
    '// A change needs a new gated run and a new checksum in src/results/registration.ts.',
    '// src/results/__tests__/persisted.test.ts recomputes every number here from the per-evening runs and checks the record',
    '// against the registration, the frozen parameters and the dataset.',
    "import type { PersistedMainResults } from './persisted';",
    '',
    `export const PERSISTED_MAIN_RESULTS: PersistedMainResults = ${JSON.stringify(p, null, 2)};`,
    '',
  ].join('\n');
}

/** A comparison by its measure and baseline, from the record. */
function find(p: PersistedMainResults, measure: Comparison['measure'], baseline: Comparison['baseline'], main: boolean): Comparison {
  const c = p.main.comparisons.find((x) => x.measure === measure && x.baseline === baseline && x.main === main);
  if (!c) throw new Error(`missing comparison ${measure} vs ${baseline}`);
  return c;
}

const readingText = (c: Comparison) =>
  c.reading === 'salo_better' ? C.saloBetter : c.reading === 'baseline_better' ? C.baselineBetter : C.noClear;

const MEASURE_LABEL: Record<Comparison['measure'], string> = {
  foodRescued: 'Food rescued (kg per evening)',
  foodWasted: 'Food wasted (kg per evening)',
  needMet: 'Need met, worst-served pantry (fraction)',
  stranded: 'Stranded awards (per evening)',
};

/** A comparison's mean and bounds in the measure's own unit: fractions to three places, kg and awards to two. */
const fmtFor = (c: Comparison) => (x: number) => signed(x, c.measure === 'needMet' ? 3 : 2);

/** Posted kg over need kg per evening (lots' estKg summed over the needs), its range, and how many evenings are below 1. */
export function supplyRatios(evenings: readonly Evening[]): { min: number; max: number; below: number } {
  const ratios = evenings.map((e) => {
    const need = e.needs.reduce((s, n) => s + n.needKg, 0);
    const posted = e.lots.reduce((s, l) => s + l.estKg, 0);
    if (need <= 0) throw new Error(`${e.id}: no need, so no supply ratio`);
    return posted / need;
  });
  return { min: Math.min(...ratios), max: Math.max(...ratios), below: ratios.filter((r) => r < 1).length };
}

/** The markdown report (docs/reports/m6-main.md). */
export function renderMainReport(
  p: PersistedMainResults,
  opts: { date: string; runtimeSeconds: number | null; evenings: readonly Evening[] },
): string {
  const food = find(p, 'foodRescued', 'central_greedy', true);
  const fair = find(p, 'needMet', 'central_greedy', true);
  const wFood = widthCheck(food);
  const wFair = widthCheck(fair);
  const supporting = p.main.comparisons.filter((c) => !c.main);
  const n = p.main.evenings.length;
  const needsOf = new Map(opts.evenings.map((e) => [e.id, e.needs]));
  const supply = supplyRatios(opts.evenings);
  const hit = (pid: PolicyId, i: number) => {
    const r = p.main.perEvening[pid][i];
    const needs = needsOf.get(r.evening);
    if (!needs) throw new Error(`no needs for ${r.evening}`);
    return reachedFoodCeiling(r, needs);
  };
  const lines: string[] = [];
  const push = (...xs: string[]) => lines.push(...xs);

  push(
    `# Main results E21–E64: the four policies on ${n} main_sample evenings`,
    '',
    `Main evenings E21–E64 (split main_sample, dataset ${p.dataset.version}). Written by the gated runner ` +
      `\`src/tuning/__tests__/m6-main-run.test.ts\` (M6_MAIN=1) on ${opts.date}. Frozen parameters ${p.frozenParamsChecksum}, ` +
      'the settings in `src/engine/frozenParams.ts`. Learning on (the engine default) for every main number. ' +
      `Paired percentile bootstrap on the difference, evening by evening: ${p.resamples.toLocaleString('en-US')} resamples, ` +
      `seed ${p.seed}. The main intervals are 97.5%, the supporting ones 95% (guide p.19). Simulated data.`,
    '',
    '## 1. The two main results (97.5%)',
    '',
    `Verdict, from the pre-registered rule (RES-04, guide p.16): **${VERDICT_LABEL[p.main.verdict]}**`,
    '',
    `Verdict line as shown on the screen: ${verdictLine({ low: food.low, high: food.high }, { low: fair.low, high: fair.high })}`,
    '',
    '| Main result (Salo minus central greedy) | Mean per evening | 97.5% interval | Reading |',
    '|---|---|---|---|',
    `| ${MEASURE_LABEL.foodRescued} | ${signed(food.mean, 2)} | [${signed(food.low, 2)}, ${signed(food.high, 2)}] | ${readingText(food)} |`,
    `| ${MEASURE_LABEL.needMet} | ${signed(fair.mean, 3)} | [${signed(fair.low, 3)}, ${signed(fair.high, 3)}] | ${readingText(fair)} |`,
    '',
    `Evenings used: ${food.evenings} for food rescued and ${fair.evenings} for need met (all main_sample).`,
    '',
    '**Fairness-gap limitation (Arjhine, decisions.md M6):** a real difference smaller than 0.10 (for example 0.15 vs 0.20) is ' +
      'treated as not worth caring about, so the main run is not sized to detect it. The fairness gap was fixed before the ' +
      'pilot and was not changed after it.',
    '',
    '**The tuned fairness floor was not reached.** On the tuning evenings E01–E10, worst-served need met was 0.151 for Salo and ' +
      '0.166 for central greedy, against the 0.5 target (decisions.md, M6 tuning). This report does not change that.',
    '',
    '## 2. Width check (Arjhine: each main 97.5% interval must be narrower than its gap)',
    '',
    '| Main result | 97.5% interval | Full width | Gap | Width below gap? |',
    '|---|---|---|---|---|',
    `| Food rescued | [${signed(food.low, 2)}, ${signed(food.high, 2)}] kg | ${f2(wFood.width)} kg | ${WIDTH_GAP_FOOD_KG} kg | ${wFood.below ? 'YES' : 'NO'} |`,
    `| Need met, worst-served | [${signed(fair.low, 3)}, ${signed(fair.high, 3)}] | ${f3(wFair.width)} | ${WIDTH_GAP_NEED_MET.toFixed(2)} | ${wFair.below ? 'YES' : 'NO'} |`,
    '',
    `Food rescued: the full 97.5% width is ${f2(wFood.width)} kg, ${wFood.below ? 'below' : 'not below'} the ${WIDTH_GAP_FOOD_KG} kg gap.`,
    `Fairness: the full 97.5% width is ${f3(wFair.width)}, ${wFair.below ? 'below' : 'not below'} the ${WIDTH_GAP_NEED_MET.toFixed(2)} gap.`,
    '',
    '## 3. Supporting comparisons (95%): supporting only, never a win on their own',
    '',
    '| Measure | Baseline | Mean (Salo minus baseline) | 95% interval | Reading |',
    '|---|---|---|---|---|',
    ...supporting.map(
      (c) =>
        `| ${MEASURE_LABEL[c.measure]} | ${LABEL[c.baseline]} | ${fmtFor(c)(c.mean)} | [${fmtFor(c)(c.low)}, ${fmtFor(c)(c.high)}] | ${readingText(c)} |`,
    ),
    '',
    '**Food wasted mirrors food rescued.** The same kg is posted under every policy, so food wasted equals posted kg minus food ' +
      'rescued. Each food-wasted interval is the exact mirror of the food-rescued interval at the same level (same resamples, sign ' +
      'reversed; checked in src/results/__tests__/persisted.test.ts). The food-rescued comparison against central greedy is the ' +
      'main result at 97.5%, so its 95% mirror is not in this table. The food-wasted rows are not independent support.',
    '',
    '## 4. Supporting: learning off (95%, supporting evidence only, guide p.15)',
    '',
    "Each policy on the same evenings with every driver's estimate fixed at 0.50 (learning off), compared with learning on, " +
      'food rescued per evening.',
    '',
    '| Policy | Evenings | Mean (on minus off, kg) | 95% interval | Reading |',
    '|---|---|---|---|---|',
    ...ORDER.map((pid) => {
      const l = p.learning[pid];
      const reading = l.reading === 'learning_helps' ? 'learning helps' : l.reading === 'learning_hurts' ? 'learning hurts' : C.noClear;
      return `| ${LABEL[pid]} | ${l.evenings} | ${signed(l.mean, 2)} | [${signed(l.low, 2)}, ${signed(l.high, 2)}] | ${reading} |`;
    }),
    '',
    '## 5. Supporting: evenings that reached the food ceiling',
    '',
    'Assumption (decisions.md, Results screen defaults): the ceiling is reached when every pantry with need is fully met, so food ' +
      'rescued equals total need. The guide does not define it.',
    '',
    '| Policy | Evenings at the food ceiling |',
    '|---|---|',
    ...ORDER.map((pid) => `| ${LABEL[pid]} | ${C.ceilingOf(p.ceilings[pid], n)} |`),
    '',
    `**Read the ceiling counts with the supply in mind.** Posted food is below total need on every main evening: the ratio of ` +
      `posted kg to need kg runs from ${supply.min.toFixed(2)} to ${supply.max.toFixed(2)} across E21–E64 (${supply.below} of ${n} ` +
      'evenings below 1.00). Under the assumption above, the ceiling cannot be reached on any of these evenings, so the zero ' +
      'counts follow from the definition, not from the policies. A different ceiling definition is an open question for Arjhine.',
    '',
    '## 6. Per-evening tables (main_sample, E21–E64)',
    '',
  );

  for (const pid of ORDER) {
    push(
      `### ${LABEL[pid]}`,
      '',
      '| Evening | Food rescued (kg) | Food wasted (kg) | Worst-served need met | Stranded awards | Food ceiling hit |',
      '|---|---|---|---|---|---|',
      ...p.main.perEvening[pid].map(
        (r, i) =>
          `| ${r.evening} | ${f2(r.foodRescuedKg)} | ${f2(r.foodWastedKg)} | ${r.worstNeedMet === null ? 'n/a' : f3(r.worstNeedMet)} | ${r.strandedAwards} | ${hit(pid, i) ? 'yes' : 'no'} |`,
      ),
      '',
    );
  }

  push(
    '### Differences d (Salo minus central greedy), evening by evening',
    '',
    '| Evening | Salo food (kg) | Central greedy food (kg) | d food (kg) | Salo worst-served | Central greedy worst-served | d need met |',
    '|---|---|---|---|---|---|---|',
    ...p.main.perEvening.salo.map((s, i) => {
      const g = p.main.perEvening.central_greedy[i];
      const dFair = s.worstNeedMet === null || g.worstNeedMet === null ? 'n/a' : signed(s.worstNeedMet - g.worstNeedMet, 3);
      return `| ${s.evening} | ${f2(s.foodRescuedKg)} | ${f2(g.foodRescuedKg)} | ${signed(s.foodRescuedKg - g.foodRescuedKg, 2)} | ${
        s.worstNeedMet === null ? 'n/a' : f3(s.worstNeedMet)
      } | ${g.worstNeedMet === null ? 'n/a' : f3(g.worstNeedMet)} | ${dFair} |`;
    }),
    '',
    '## Checks and limits',
    '',
    `- Dataset ${p.dataset.version}: bundled tables sha256 ${p.dataset.bundledTablesSha256}; dataset repo manifest ${p.dataset.datasetRepoManifestSha256}.`,
    `- Main evenings: ${p.dataset.mainEvenings.join(', ')} (${p.mainEveningCount} recorded).`,
    `- Runtime of the gated run: ${opts.runtimeSeconds === null ? 'not recorded' : `${opts.runtimeSeconds.toFixed(1)} s`} (four policies, learning on and off, sequential).`,
    '- Food ceiling: the assumption in section 5.',
    '- No pilot or tuning evening appears in this report. The tuning and pilot numbers are not results.',
    '- The numbers are simulated (Salo Evening Dataset). They say nothing about real pantries.',
    '',
  );
  return lines.join('\n');
}
